const FALLBACK = '#a8a878'

export function typeColor(type: string): string {
  return TYPE_COLORS[type] ?? FALLBACK
}

/**
 * Texto escuro nos tipos claros (Elétrico, Gelo, Terra...), branco nos
 * escuros. O branco vai com sombra, então ganha até uma luminância um pouco
 * acima do ponto de contraste igual.
 */
export function typeInk(type: string): string {
  const hex = typeColor(type).slice(1)
  const [r, g, b] = [0, 2, 4].map((at) => {
    const c = parseInt(hex.slice(at, at + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  const luminance = 0.2126 * r! + 0.7152 * g! + 0.0722 * b!
  return luminance > 0.35 ? '#181820' : '#ffffff'
}

function grid(rows: string[]): { x: number; y: number }[] {
  return rows.flatMap((line, y) => [...line].flatMap((cell, x) => (cell === 'X' ? [{ x, y }] : [])))
}

